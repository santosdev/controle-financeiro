-- Esquema inicial do FinanceControl com contas de usuario (PostgreSQL).
-- Cada categoria e cada movimentacao pertence a um usuario.
-- Enums ficam como VARCHAR com CHECK; datas e horas em TIMESTAMPTZ (UTC).

CREATE TABLE usuarios (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(100) NOT NULL,
    email             VARCHAR(160) NOT NULL,
    senha_hash        VARCHAR(100) NULL,
    provedor          VARCHAR(10)  NOT NULL,
    email_verificado  BOOLEAN      NOT NULL,
    tentativas_falhas INT          NOT NULL,
    bloqueado_ate     TIMESTAMPTZ  NULL,
    criado_em         TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_provedor CHECK (provedor IN ('LOCAL', 'GOOGLE'))
);

-- Tokens de uso unico enviados por e-mail (confirmar conta e redefinir senha).
-- Guardamos apenas o hash (SHA-256): quem ler o banco nao consegue usar os links.
CREATE TABLE tokens_usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT      NOT NULL,
    tipo       VARCHAR(20) NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expira_em  TIMESTAMPTZ NOT NULL,
    usado_em   TIMESTAMPTZ NULL,
    criado_em  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_tokens_tipo CHECK (tipo IN ('VERIFICACAO_EMAIL', 'REDEFINICAO_SENHA')),
    CONSTRAINT fk_tokens_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);
CREATE INDEX idx_tokens_usuario_tipo ON tokens_usuario (usuario_id, tipo);

CREATE TABLE categorias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT      NOT NULL,
    nome       VARCHAR(60) NOT NULL,
    tipo       VARCHAR(10) NOT NULL,
    CONSTRAINT ck_categorias_tipo CHECK (tipo IN ('RECEITA', 'DESPESA')),
    CONSTRAINT fk_categorias_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);
CREATE INDEX idx_categorias_usuario ON categorias (usuario_id);

CREATE TABLE transacoes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT        NOT NULL,
    categoria_id BIGINT        NOT NULL,
    descricao    VARCHAR(120)  NOT NULL,
    valor        NUMERIC(12,2) NOT NULL,
    data         DATE          NOT NULL,
    tipo         VARCHAR(10)   NOT NULL,
    CONSTRAINT ck_transacoes_tipo CHECK (tipo IN ('RECEITA', 'DESPESA')),
    CONSTRAINT fk_transacoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_transacoes_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id)
);
CREATE INDEX idx_transacoes_usuario_data ON transacoes (usuario_id, data);
CREATE INDEX idx_transacoes_categoria ON transacoes (categoria_id);
